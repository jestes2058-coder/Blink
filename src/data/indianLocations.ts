export function getDistrictsForState(stateName: string): string[] {
  const match = INDIAN_STATES_AND_DISTRICTS.find(
    (s) => s.state.toLowerCase() === stateName.toLowerCase(),
  )
  if (match) return match.districts
  // Fallback to Kerala districts if state is not found
  return INDIAN_STATES_AND_DISTRICTS[0].districts
}

